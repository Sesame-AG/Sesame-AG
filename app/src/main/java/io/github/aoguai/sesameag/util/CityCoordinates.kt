    /**
     * 经纬度最近邻城市匹配（haversine 球面距离）。
     * 距最近城市中心超过 [maxDistanceKm] 视为离城市过远，返回 null（继续走后续降级）。
     */
    fun nearestCityCode(latitude: Double, longitude: Double, maxDistanceKm: Double = 150.0): String? {
        if (!latitude.isFinite() || !longitude.isFinite()) return null
        var bestCode: String? = null
        var bestDistance = Double.MAX_VALUE
        for (city in CITIES) {
            val d = haversineKm(latitude, longitude, city.lat, city.lon)
            if (d < bestDistance) {
                bestDistance = d
                bestCode = city.code
            }
        }
        return if (bestDistance <= maxDistanceKm) bestCode else null
    }

    private fun haversineKm(lat1: Double, lon1: Double, lat2: Double, lon2: Double): Double {
        val dLat = Math.toRadians(lat2 - lat1)
        val dLon = Math.toRadians(lon2 - lon1)
        val a = sin(dLat / 2) * sin(dLat / 2) +
            cos(Math.toRadians(lat1)) * cos(Math.toRadians(lat2)) * sin(dLon / 2) * sin(dLon / 2)
        return 2 * 6371.0 * asin(sqrt(a))
    }
